# 已知城市名（去重后的快速判定集合）
_KNOWN_SET = set(KNOWN_CITIES)
# 真实城市清单按长度降序，保证「武夷山」优先于「武」之类
_REAL_SORTED = sorted(set(REAL_CITIES), key=len, reverse=True)


def detect_city(question: str) -> tuple[str | None, bool]:
    """识别提问中点名的城市。

    Returns:
        (city_name, in_kb)
        - city_name: 命中的城市/景区名；未命中任何已知真实地名返回 None
        - in_kb: 该地是否在知识库中（True=命中 KB 城市）
    匹配优先级：已知城市（最长优先） > 真实城市清单（最长优先） > 别称映射。
    """
    q = question or ""
    # 1) 已知 KB 城市（最长优先，避免「南京」被「京」误伤等）
    for city in KNOWN_CITIES:
        if city in q:
            return city, True
    # 2) 其它真实城市/景区
    for city in _REAL_SORTED:
        if city in q:
            return city, False
    # 3) 别称映射
    for alias, std in ALIASES.items():
        if alias in q:
            return std, std in _KNOWN_SET
    return None, False


def is_known_city(question: str) -> bool:
    """提问是否点名了知识库中已收录的城市。"""
    _, in_kb = detect_city(question)
    return in_kb
